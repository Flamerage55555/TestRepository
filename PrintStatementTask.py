# basic string output
print("Hello, World!") 

# simple math inside print
print(5 + 3) 

# multiple arguements in print
print("Python", "is", "fun!") 

# print with escape characters
print("She said, \"Hello!\"") 

# Newline Character
print("First line\nSecond line")

# Tab Character
print("Item 1\tItem 2\tItem 3")

# Print Multiple Data Types Together
print("The result is", 42)

# Print a Single Number
print(12345)

# Print a Decimal Number
print(3.14159)

# Print Special Characters
print("Dollar sign: $")

# Using the sep Parameter
print("apple", "banana", "cherry", sep=", ")

# Using the end Parameter
print("Hello,", end=" ")
print("World!")

# Print a Repeated String
print("Python! " * 3)

# Print a Unicode Character (heart symbol)
print("\u2764") 

# Print Empty Line
print()

# Concatenating Strings Inside Print
print("Hello " + "World!")

# Print Boolean Values
print(True)
print(False)

# Printing Exponential Notation
print(1.2e3) # Prints 1200.0

# Print Multiline Text Using Triple Quotes
print("""This is a multiline
print statement.""")

# Print Using Escaped Backslash
print("This is a backslash: \\")

